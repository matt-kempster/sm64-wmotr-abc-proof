Section CHK.
Variable F V : Type.
Variable ge : Globalenvs.Genv.t F V.

Lemma chk_sound : forall l p cs m b,
  Globalenvs.Genv.load_store_init_data ge m b p l -> chk l p cs = true ->
  forall o ch z, In (o, ch, z) cs -> Mem.load ch m b o = Some (Vint (Int.repr z)).
Proof.
  induction l as [| d l IH]; intros p cs m b LS C o ch z Hin.
  - destruct cs as [| [[o1 ch1] z1] cs]; [destruct Hin | discriminate C].
  - destruct cs as [| [[o1 ch1] z1] cs]; [destruct Hin |].
    cbn [chk] in C.
    destruct (Z.eqb_spec p o1) as [<- | N].
    + apply andb_prop in C as [Cd C].
      destruct Hin as [E | Hin].
      * injection E as -> -> ->.
        destruct d; cbn [cell_ok] in Cd; destruct ch; try discriminate Cd;
          apply Int.same_if_eq in Cd; cbn [Globalenvs.Genv.load_store_init_data] in LS.
        -- rewrite Mem.load_int16_signed_unsigned. rewrite (proj1 LS). cbn. rewrite Cd. reflexivity.
        -- rewrite (proj1 LS). rewrite Cd. reflexivity.
        -- rewrite (proj1 LS). rewrite Cd. reflexivity.
      * cbn [Globalenvs.Genv.load_store_init_data] in LS.
        assert (LS' : Globalenvs.Genv.load_store_init_data ge m b (p + init_data_size d) l)
          by (destruct d; destruct LS as [_ LS]; try exact LS; destruct LS as [_ LS]; exact LS).
        exact (IH _ _ _ _ LS' C o ch z Hin).
    + destruct (Z.ltb p o1); [| discriminate C].
      cbn [Globalenvs.Genv.load_store_init_data] in LS.
      assert (LS' : Globalenvs.Genv.load_store_init_data ge m b (p + init_data_size d) l)
        by (destruct d; destruct LS as [_ LS]; try exact LS; destruct LS as [_ LS]; exact LS).
      exact (IH _ _ _ _ LS' C o ch z Hin).
Qed.
End CHK.
