(* what a chunk read of init datum d holds, as Genv.load_store_init_data
   stores it *)
Definition cell_ok (d : init_data) (ch : memory_chunk) (z : Z) : bool :=
  match d, ch with
  | Init_int32 n, Mint32 => Int.eq (Int.repr z) n
  | Init_int16 n, Mint16signed => Int.eq (Int.repr z) (Int.sign_ext 16 (Int.zero_ext 16 n))
  | Init_int16 n, Mint16unsigned => Int.eq (Int.repr z) (Int.zero_ext 16 n)
  | _, _ => false
  end.

(* one pass over the initializer (p: the current offset) and the cells,
   sorted by offset *)
Fixpoint chk (l : list init_data) (p : Z) (cs : list (Z * memory_chunk * Z)) {struct l} : bool :=
  match cs with
  | [] => true
  | (o, ch, z) :: cs' =>
      match l with
      | [] => false
      | d :: l' =>
          if Z.eqb p o then cell_ok d ch z && chk l' (p + init_data_size d) cs'
          else if Z.ltb p o then chk l' (p + init_data_size d) cs
          else false
      end
  end.

